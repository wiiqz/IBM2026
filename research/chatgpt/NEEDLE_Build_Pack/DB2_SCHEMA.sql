-- NEEDLE / IBM Db2 LUW 12.1.5; intended for a NEW dedicated test database.
-- SQL is grounded in Db2 12.1 docs but NOT EXECUTED against a live Db2 by the spec author.
-- Execute in statement order, e.g. db2 -tvf DB2_SCHEMA.sql using Db2 CLP.
-- If the target has no CREATE BUFFERPOOL/TABLESPACE privilege, administrator must provision NDL_TS32.
-- Mandatory for 768-d FLOAT32 indexed vectors: 32K table/index page size (IBM index key <= 1/4 page).
-- Never run this on a production database. No DROP statements included.

CREATE BUFFERPOOL NDL_BP32 SIZE 1024 PAGESIZE 32K;
CREATE LARGE TABLESPACE NDL_TS32 PAGESIZE 32K MANAGED BY AUTOMATIC STORAGE BUFFERPOOL NDL_BP32;

CREATE TABLE NDL_ADVISORIES (
  ADV_ID           VARCHAR(64) NOT NULL,
  TITLE            VARCHAR(300) NOT NULL,
  SUMMARY          CLOB(16K) NOT NULL,
  SOURCE_URL       VARCHAR(1024) NOT NULL,
  SOURCE_KIND      VARCHAR(16) NOT NULL,
  VISIBILITY       VARCHAR(16) NOT NULL DEFAULT 'PUBLIC',
  PUBLISHED_AT     TIMESTAMP,
  CVSS_SCORE       DECIMAL(4,1),
  EMBED_MODEL      VARCHAR(100) NOT NULL,
  EMBEDDING        VECTOR(768, FLOAT32) NOT NULL,
  CREATED_AT       TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
  CONSTRAINT NDL_PK_ADV PRIMARY KEY (ADV_ID),
  CONSTRAINT NDL_CK_SOURCE CHECK (SOURCE_KIND IN ('SYNTHETIC', 'OSV', 'CVE')),
  CONSTRAINT NDL_CK_VIS CHECK (VISIBILITY IN ('PUBLIC', 'EMBARGOED')),
  CONSTRAINT NDL_CK_SCORE CHECK (CVSS_SCORE IS NULL OR (CVSS_SCORE BETWEEN 0 AND 10))
) IN NDL_TS32;

CREATE TABLE NDL_ADVISORY_TERMS (
  ADV_ID       VARCHAR(64) NOT NULL,
  TERM_TOKEN   VARCHAR(90) NOT NULL,
  TERM_WEIGHT  INTEGER NOT NULL DEFAULT 1,
  CONSTRAINT NDL_PK_TERMS PRIMARY KEY (ADV_ID, TERM_TOKEN),
  CONSTRAINT NDL_FK_TERMS FOREIGN KEY (ADV_ID) REFERENCES NDL_ADVISORIES(ADV_ID),
  CONSTRAINT NDL_CK_WEIGHT CHECK (TERM_WEIGHT BETWEEN 1 AND 100)
) IN NDL_TS32;
CREATE INDEX NDL_IX_TERMS_TOKEN ON NDL_ADVISORY_TERMS(TERM_TOKEN, ADV_ID);

CREATE TABLE NDL_PACKAGES (
  PKG_ID       BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY,
  ECOSYSTEM    VARCHAR(40) NOT NULL,
  PKG_NAME     VARCHAR(240) NOT NULL,
  CONSTRAINT NDL_PK_PACKAGES PRIMARY KEY (PKG_ID),
  CONSTRAINT NDL_UQ_PACKAGES UNIQUE (ECOSYSTEM, PKG_NAME)
) IN NDL_TS32;

-- Exact affected releases are intentionally modeled explicitly; no arbitrary semver/PEP440 range inference.
CREATE TABLE NDL_AFFECTED_RELEASES (
  ADV_ID         VARCHAR(64) NOT NULL,
  PKG_ID         BIGINT NOT NULL,
  EXACT_VERSION  VARCHAR(100) NOT NULL,
  CONSTRAINT NDL_PK_AFFECTED PRIMARY KEY (ADV_ID, PKG_ID, EXACT_VERSION),
  CONSTRAINT NDL_FK_AFF_ADV FOREIGN KEY (ADV_ID) REFERENCES NDL_ADVISORIES(ADV_ID),
  CONSTRAINT NDL_FK_AFF_PKG FOREIGN KEY (PKG_ID) REFERENCES NDL_PACKAGES(PKG_ID)
) IN NDL_TS32;
CREATE INDEX NDL_IX_AFFECTED_PKG ON NDL_AFFECTED_RELEASES(PKG_ID, EXACT_VERSION, ADV_ID);

CREATE TABLE NDL_SBOMS (
  SBOM_ID      VARCHAR(40) NOT NULL,
  LABEL        VARCHAR(140) NOT NULL,
  SOURCE_TYPE  VARCHAR(20) NOT NULL,
  CREATED_AT   TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
  CONSTRAINT NDL_PK_SBOMS PRIMARY KEY (SBOM_ID),
  CONSTRAINT NDL_CK_SBOM_TYPE CHECK (SOURCE_TYPE IN ('SYNTHETIC', 'CYCLONEDX', 'SPDX'))
) IN NDL_TS32;

CREATE TABLE NDL_SBOM_COMPONENTS (
  SBOM_ID        VARCHAR(40) NOT NULL,
  COMPONENT_ID   VARCHAR(64) NOT NULL,
  PKG_ID         BIGINT NOT NULL,
  INSTALLED_VER  VARCHAR(100) NOT NULL,
  DIRECT_DEP     SMALLINT NOT NULL DEFAULT 1,
  CONSTRAINT NDL_PK_COMPONENTS PRIMARY KEY (SBOM_ID, COMPONENT_ID),
  CONSTRAINT NDL_FK_COMP_SBOM FOREIGN KEY (SBOM_ID) REFERENCES NDL_SBOMS(SBOM_ID),
  CONSTRAINT NDL_FK_COMP_PKG FOREIGN KEY (PKG_ID) REFERENCES NDL_PACKAGES(PKG_ID),
  CONSTRAINT NDL_CK_DEP CHECK (DIRECT_DEP IN (0,1))
) IN NDL_TS32;
CREATE INDEX NDL_IX_COMPONENTS_PKG ON NDL_SBOM_COMPONENTS(PKG_ID, INSTALLED_VER);

-- Query terms are short-lived, keyed by request UUID, cleaned up after query and on startup.
CREATE TABLE NDL_QUERY_TERMS (
  QUERY_ID       VARCHAR(40) NOT NULL,
  TERM_TOKEN     VARCHAR(90) NOT NULL,
  CREATED_AT     TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
  CONSTRAINT NDL_PK_QTERMS PRIMARY KEY (QUERY_ID, TERM_TOKEN)
) IN NDL_TS32;
CREATE INDEX NDL_IX_QTERMS_TIME ON NDL_QUERY_TERMS(CREATED_AT);

CREATE TABLE NDL_BENCHMARK_RUNS (
  RUN_ID         VARCHAR(40) NOT NULL,
  QUERY_SET_SHA  VARCHAR(64) NOT NULL,
  DATASET_SHA    VARCHAR(64) NOT NULL,
  MODEL_NAME     VARCHAR(100) NOT NULL,
  DB2_VERSION    VARCHAR(90) NOT NULL,
  MODE           VARCHAR(20) NOT NULL,
  K              INTEGER NOT NULL,
  QUERY_COUNT    INTEGER NOT NULL,
  MEDIAN_MS      DOUBLE,
  P95_MS         DOUBLE,
  RECALL_AT_K    DOUBLE,
  INDEX_USED     SMALLINT,
  CAPTURED_AT    TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
  CONSTRAINT NDL_PK_BENCH PRIMARY KEY (RUN_ID),
  CONSTRAINT NDL_CK_BENCHMODE CHECK (MODE IN ('KEYWORD','EXACT','APPROX','HYBRID')),
  CONSTRAINT NDL_CK_INDEX_USED CHECK (INDEX_USED IS NULL OR INDEX_USED IN (0,1))
) IN NDL_TS32;

CREATE INDEX NDL_IX_ADV_VIS ON NDL_ADVISORIES(VISIBILITY, PUBLISHED_AT);

